let currentLang = localStorage.getItem('monstera_lang') || 'ko';

window.setLanguage = function(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('monstera_lang', lang);

  // Update text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update input placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('placeholder', translations[lang][key]);
    }
  });

  // Update HTML lang attribute and document title
  document.documentElement.lang = lang;
  if (translations[lang]['site-title']) {
    document.title = translations[lang]['site-title'];
  }

  // Update GNB language button label
  const currentLangLabel = document.getElementById('lang-current');
  if (currentLangLabel) {
    currentLangLabel.textContent = lang === 'en' ? 'English' : '한국어';
  }

  // Update active state in dropdown options
  document.querySelectorAll('.lang-option').forEach(opt => {
    const isTarget = opt.getAttribute('data-lang') === lang;
    opt.classList.toggle('active', isTarget);
  });

  // Update active state in mobile drawer
  document.querySelectorAll('.lang-btn-drawer').forEach(opt => {
    const isTarget = opt.getAttribute('data-lang') === lang;
    opt.classList.toggle('active', isTarget);
  });

  // Close dropdown menu after selection
  const langDropdown = document.getElementById('lang-dropdown');
  const langWrap = document.querySelector('.lang-select-wrap');
  if (langDropdown) langDropdown.classList.remove('show');
  if (langWrap) langWrap.classList.remove('active');

  // Re-render dynamic gallery if gallery module exists
  if (window.renderGallery) {
    window.renderGallery();
  }
};

window.toggleLangDropdown = function(e) {
  if (e) {
    e.stopPropagation();
    e.preventDefault();
  }
  const langDropdown = document.getElementById('lang-dropdown');
  const langWrap = document.querySelector('.lang-select-wrap');
  if (langDropdown) {
    const isShowing = langDropdown.classList.toggle('show');
    if (langWrap) langWrap.classList.toggle('active', isShowing);
  }
};

function initI18n() {
  window.setLanguage(currentLang);

  const langWrap = document.querySelector('.lang-select-wrap');
  document.addEventListener('click', (e) => {
    if (langWrap && !langWrap.contains(e.target)) {
      const langDropdown = document.getElementById('lang-dropdown');
      if (langDropdown) langDropdown.classList.remove('show');
      langWrap.classList.remove('active');
    }
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
